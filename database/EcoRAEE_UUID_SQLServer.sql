IF NOT EXISTS (SELECT name FROM sys.databases WHERE name = N'EcoRAEE_DB')
BEGIN
    CREATE DATABASE EcoRAEE_DB;
END
GO

USE EcoRAEE_DB;
GO

-- Limpiar tablas en orden inverso de dependencias (solo para recreación limpia)
IF OBJECT_ID(N'dbo.AUDITORIA', N'U') IS NOT NULL DROP TABLE dbo.AUDITORIA;
IF OBJECT_ID(N'dbo.ALERTA', N'U') IS NOT NULL DROP TABLE dbo.ALERTA;
IF OBJECT_ID(N'dbo.INDICADOR', N'U') IS NOT NULL DROP TABLE dbo.INDICADOR;
IF OBJECT_ID(N'dbo.ESCENARIO', N'U') IS NOT NULL DROP TABLE dbo.ESCENARIO;
IF OBJECT_ID(N'dbo.ARISTA', N'U') IS NOT NULL DROP TABLE dbo.ARISTA;
IF OBJECT_ID(N'dbo.NODO', N'U') IS NOT NULL DROP TABLE dbo.NODO;
IF OBJECT_ID(N'dbo.INVENTARIO', N'U') IS NOT NULL DROP TABLE dbo.INVENTARIO;
IF OBJECT_ID(N'dbo.EVIDENCIA', N'U') IS NOT NULL DROP TABLE dbo.EVIDENCIA;
IF OBJECT_ID(N'dbo.TRATAMIENTO', N'U') IS NOT NULL DROP TABLE dbo.TRATAMIENTO;
IF OBJECT_ID(N'dbo.TRANSFERENCIA_MOVIMIENTO', N'U') IS NOT NULL DROP TABLE dbo.TRANSFERENCIA_MOVIMIENTO;
IF OBJECT_ID(N'dbo.HISTORIAL_ESTADOS', N'U') IS NOT NULL DROP TABLE dbo.HISTORIAL_ESTADOS;
IF OBJECT_ID(N'dbo.EVALUACION_TECNICA', N'U') IS NOT NULL DROP TABLE dbo.EVALUACION_TECNICA;
IF OBJECT_ID(N'dbo.DISPOSITIVO', N'U') IS NOT NULL DROP TABLE dbo.DISPOSITIVO;
IF OBJECT_ID(N'dbo.LOTE', N'U') IS NOT NULL DROP TABLE dbo.LOTE;
IF OBJECT_ID(N'dbo.SOLICITUD', N'U') IS NOT NULL DROP TABLE dbo.SOLICITUD;
IF OBJECT_ID(N'dbo.OBJETO', N'U') IS NOT NULL DROP TABLE dbo.OBJETO;
IF OBJECT_ID(N'dbo.CATEGORIA', N'U') IS NOT NULL DROP TABLE dbo.CATEGORIA;
IF OBJECT_ID(N'dbo.CENTRO', N'U') IS NOT NULL DROP TABLE dbo.CENTRO;
IF OBJECT_ID(N'dbo.TIPO_CENTRO', N'U') IS NOT NULL DROP TABLE dbo.TIPO_CENTRO;
IF OBJECT_ID(N'dbo.CONDICION', N'U') IS NOT NULL DROP TABLE dbo.CONDICION;
IF OBJECT_ID(N'dbo.ESTADO_CATALOGO', N'U') IS NOT NULL DROP TABLE dbo.ESTADO_CATALOGO;
IF OBJECT_ID(N'dbo.USUARIO', N'U') IS NOT NULL DROP TABLE dbo.USUARIO;
IF OBJECT_ID(N'dbo.ROL', N'U') IS NOT NULL DROP TABLE dbo.ROL;
IF OBJECT_ID(N'dbo.ORGANIZACION', N'U') IS NOT NULL DROP TABLE dbo.ORGANIZACION;
GO

-- 1. ACTORES Y SEGURIDAD RBAC
CREATE TABLE dbo.ORGANIZACION (
    id_organizacion UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    ruc NVARCHAR(13) NOT NULL UNIQUE,
    razon_social NVARCHAR(150) NOT NULL,
    direccion NVARCHAR(200) NULL,
    telefono NVARCHAR(30) NULL,
    CONSTRAINT CK_ORGANIZACION_RUC CHECK (LEN(ruc) = 13 AND ruc NOT LIKE '%[^0-9]%')
);

CREATE TABLE dbo.ROL (
    id_rol UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    nombre_rol NVARCHAR(60) NOT NULL UNIQUE,
    descripcion NVARCHAR(250) NULL
);

CREATE TABLE dbo.USUARIO (
    id_usuario UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    nombre NVARCHAR(100) NOT NULL,
    correo NVARCHAR(100) NOT NULL UNIQUE,
    id_organizacion UNIQUEIDENTIFIER NOT NULL,
    id_rol UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_USUARIO_ORG FOREIGN KEY (id_organizacion) REFERENCES dbo.ORGANIZACION(id_organizacion),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (id_rol) REFERENCES dbo.ROL(id_rol)
);

-- 2. CATÁLOGOS CONTROLADOS (CENTROS, CATEGORÍAS, OBJETOS, CONDICIONES, ESTADOS)
CREATE TABLE dbo.TIPO_CENTRO (
    id_tipo_centro UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    nombre_tipo NVARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE dbo.CENTRO (
    id_centro UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_centro NVARCHAR(20) NOT NULL UNIQUE,
    nombre_centro NVARCHAR(120) NOT NULL,
    direccion NVARCHAR(200) NOT NULL,
    ciudad NVARCHAR(80) NULL DEFAULT N'Quito',
    capacidad_max_ton DECIMAL(10,2) NOT NULL DEFAULT 50.00,
    id_tipo_centro UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_CENTRO_TIPO FOREIGN KEY (id_tipo_centro) REFERENCES dbo.TIPO_CENTRO(id_tipo_centro)
);

CREATE TABLE dbo.CATEGORIA (
    id_categoria UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_categoria NVARCHAR(30) NOT NULL UNIQUE,
    nombre_categoria NVARCHAR(100) NOT NULL UNIQUE,
    descripcion NVARCHAR(250) NULL
);

CREATE TABLE dbo.OBJETO (
    id_objeto UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_objeto NVARCHAR(30) NOT NULL UNIQUE,
    nombre_objeto NVARCHAR(120) NOT NULL UNIQUE,
    marca NVARCHAR(50) NOT NULL,
    modelo NVARCHAR(60) NOT NULL,
    descripcion NVARCHAR(250) NULL,
    peso_estimado_kg DECIMAL(8,2) NULL,
    id_categoria UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_OBJETO_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES dbo.CATEGORIA(id_categoria)
);

CREATE TABLE dbo.CONDICION (
    id_condicion UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    descripcion_condicion NVARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE dbo.ESTADO_CATALOGO (
    id_estado UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    orden INT NOT NULL UNIQUE,
    nombre_estado NVARCHAR(60) NOT NULL UNIQUE
);

-- 3. TRAZABILIDAD RAEE
CREATE TABLE dbo.SOLICITUD (
    id_solicitud UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_solicitud NVARCHAR(30) NOT NULL UNIQUE,
    fecha_solicitud DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    estado_recoleccion NVARCHAR(30) NOT NULL,
    id_centro UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_SOLICITUD_CENTRO FOREIGN KEY (id_centro) REFERENCES dbo.CENTRO(id_centro),
    CONSTRAINT CK_SOLICITUD_ESTADO CHECK (estado_recoleccion IN ('Pendiente', 'Asignada', 'En Recoleccion', 'Finalizada'))
);

CREATE TABLE dbo.LOTE (
    id_lote UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_lote NVARCHAR(30) NOT NULL UNIQUE,
    fecha_creacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    id_solicitud UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_LOTE_SOLICITUD FOREIGN KEY (id_solicitud) REFERENCES dbo.SOLICITUD(id_solicitud)
);

CREATE TABLE dbo.DISPOSITIVO (
    id_dispositivo UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    num_serie NVARCHAR(60) NOT NULL UNIQUE,
    id_objeto UNIQUEIDENTIFIER NOT NULL,
    id_categoria UNIQUEIDENTIFIER NOT NULL,
    id_lote UNIQUEIDENTIFIER NOT NULL,
    fecha_registro DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT FK_DISPOSITIVO_OBJETO FOREIGN KEY (id_objeto) REFERENCES dbo.OBJETO(id_objeto),
    CONSTRAINT FK_DISPOSITIVO_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES dbo.CATEGORIA(id_categoria),
    CONSTRAINT FK_DISPOSITIVO_LOTE FOREIGN KEY (id_lote) REFERENCES dbo.LOTE(id_lote)
);

CREATE TABLE dbo.EVALUACION_TECNICA (
    id_evaluacion UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    fecha_evaluacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    diagnostico NVARCHAR(250) NOT NULL,
    clasificacion_tecnica NVARCHAR(40) NOT NULL,
    id_dispositivo UNIQUEIDENTIFIER NOT NULL UNIQUE,
    id_condicion UNIQUEIDENTIFIER NOT NULL,
    id_usuario_evaluador UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT CK_EVAL_CLASIFICACION CHECK (clasificacion_tecnica IN ('Reutilizacion', 'Reacondicionamiento', 'Reciclaje', 'Disposicion Final')),
    CONSTRAINT FK_EVAL_DISPOSITIVO FOREIGN KEY (id_dispositivo) REFERENCES dbo.DISPOSITIVO(id_dispositivo),
    CONSTRAINT FK_EVAL_CONDICION FOREIGN KEY (id_condicion) REFERENCES dbo.CONDICION(id_condicion),
    CONSTRAINT FK_EVAL_USUARIO FOREIGN KEY (id_usuario_evaluador) REFERENCES dbo.USUARIO(id_usuario)
);

CREATE TABLE dbo.HISTORIAL_ESTADOS (
    id_historial UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    id_dispositivo UNIQUEIDENTIFIER NOT NULL,
    id_secuencia INT NOT NULL,
    id_estado UNIQUEIDENTIFIER NOT NULL,
    fecha_cambio DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    observacion NVARCHAR(250) NULL,
    CONSTRAINT FK_HIST_DISPOSITIVO FOREIGN KEY (id_dispositivo) REFERENCES dbo.DISPOSITIVO(id_dispositivo),
    CONSTRAINT FK_HIST_ESTADO FOREIGN KEY (id_estado) REFERENCES dbo.ESTADO_CATALOGO(id_estado)
);

CREATE TABLE dbo.TRANSFERENCIA_MOVIMIENTO (
    id_movimiento UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    fecha_movimiento DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    estado_transferencia NVARCHAR(30) NOT NULL,
    id_centro_origen UNIQUEIDENTIFIER NOT NULL,
    id_centro_destino UNIQUEIDENTIFIER NOT NULL,
    id_dispositivo UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT CK_MOV_CENTROS_DISTINTOS CHECK (id_centro_origen <> id_centro_destino),
    CONSTRAINT FK_MOV_ORIGEN FOREIGN KEY (id_centro_origen) REFERENCES dbo.CENTRO(id_centro),
    CONSTRAINT FK_MOV_DESTINO FOREIGN KEY (id_centro_destino) REFERENCES dbo.CENTRO(id_centro),
    CONSTRAINT FK_MOV_DISPOSITIVO FOREIGN KEY (id_dispositivo) REFERENCES dbo.DISPOSITIVO(id_dispositivo)
);

CREATE TABLE dbo.TRATAMIENTO (
    id_tratamiento UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    resultado NVARCHAR(150) NOT NULL,
    destino NVARCHAR(150) NOT NULL,
    fecha_cierre DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    id_dispositivo UNIQUEIDENTIFIER NOT NULL UNIQUE,
    CONSTRAINT FK_TRAT_DISPOSITIVO FOREIGN KEY (id_dispositivo) REFERENCES dbo.DISPOSITIVO(id_dispositivo)
);

CREATE TABLE dbo.EVIDENCIA (
    id_evidencia UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    nombre_archivo NVARCHAR(150) NOT NULL,
    tipo_archivo NVARCHAR(30) NOT NULL,
    url_archivo NVARCHAR(500) NOT NULL,
    id_tratamiento UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT CK_EVIDENCIA_TIPO CHECK (tipo_archivo IN ('PDF', 'JPG', 'PNG', 'DOCX')),
    CONSTRAINT FK_EVIDENCIA_TRAT FOREIGN KEY (id_tratamiento) REFERENCES dbo.TRATAMIENTO(id_tratamiento)
);

CREATE TABLE dbo.INVENTARIO (
    id_inventario UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    stock_actual INT NOT NULL DEFAULT 0,
    fecha_actualizacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    id_centro UNIQUEIDENTIFIER NOT NULL,
    id_categoria UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT CK_INVENTARIO_STOCK CHECK (stock_actual >= 0),
    CONSTRAINT FK_INV_CENTRO FOREIGN KEY (id_centro) REFERENCES dbo.CENTRO(id_centro),
    CONSTRAINT FK_INV_CATEGORIA FOREIGN KEY (id_categoria) REFERENCES dbo.CATEGORIA(id_categoria)
);

-- 4. RED MATEMÁTICA, ALERTAS Y AUDITORÍA
CREATE TABLE dbo.NODO (
    id_nodo UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    id_centro UNIQUEIDENTIFIER NULL,
    tipo_nodo NVARCHAR(50) NOT NULL,
    capacidad_nodo DECIMAL(10,2) NOT NULL,
    CONSTRAINT CK_NODO_CAPACIDAD CHECK (capacidad_nodo > 0),
    CONSTRAINT FK_NODO_CENTRO FOREIGN KEY (id_centro) REFERENCES dbo.CENTRO(id_centro)
);

CREATE TABLE dbo.ARISTA (
    id_arista UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    distancia_km DECIMAL(8,2) NOT NULL,
    tiempo_estimado_min INT NOT NULL,
    id_nodo_origen UNIQUEIDENTIFIER NOT NULL,
    id_nodo_destino UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT CK_ARISTA_NODOS_DISTINTOS CHECK (id_nodo_origen <> id_nodo_destino),
    CONSTRAINT FK_ARISTA_ORIGEN FOREIGN KEY (id_nodo_origen) REFERENCES dbo.NODO(id_nodo),
    CONSTRAINT FK_ARISTA_DESTINO FOREIGN KEY (id_nodo_destino) REFERENCES dbo.NODO(id_nodo)
);

CREATE TABLE dbo.ESCENARIO (
    id_escenario UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    codigo_escenario NVARCHAR(30) NOT NULL UNIQUE,
    resultado NVARCHAR(150) NOT NULL
);

CREATE TABLE dbo.INDICADOR (
    id_indicador UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    nombre_indicador NVARCHAR(100) NOT NULL,
    valor_meta DECIMAL(12,2) NOT NULL,
    valor_actual DECIMAL(12,2) NOT NULL,
    periodo NVARCHAR(20) NOT NULL,
    id_escenario UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_INDICADOR_ESC FOREIGN KEY (id_escenario) REFERENCES dbo.ESCENARIO(id_escenario)
);

CREATE TABLE dbo.ALERTA (
    id_alerta UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    fecha_generacion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    nivel_criticidad NVARCHAR(20) NOT NULL,
    mensaje NVARCHAR(250) NOT NULL,
    estado_alerta NVARCHAR(30) NOT NULL DEFAULT N'Activa',
    id_centro UNIQUEIDENTIFIER NOT NULL,
    CONSTRAINT FK_ALERTA_CENTRO FOREIGN KEY (id_centro) REFERENCES dbo.CENTRO(id_centro)
);

CREATE TABLE dbo.AUDITORIA (
    id_auditoria UNIQUEIDENTIFIER NOT NULL DEFAULT NEWID() PRIMARY KEY,
    fecha_accion DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    tabla_afectada NVARCHAR(60) NOT NULL,
    tipo_operacion NVARCHAR(20) NOT NULL,
    detalle NVARCHAR(500) NOT NULL,
    id_usuario UNIQUEIDENTIFIER NULL,
    CONSTRAINT FK_AUDITORIA_USUARIO FOREIGN KEY (id_usuario) REFERENCES dbo.USUARIO(id_usuario)
);
GO

PRINT 'Esquema EcoRAEE Cloud (UUID + Catálogo OBJETO) creado exitosamente. Al iniciar FastAPI se poblarán los datos iniciales si la BD está vacía.';
GO
